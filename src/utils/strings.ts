export function t(key: keyof typeof strings['ar'], lang: Language, ...args: (string | number)[]): string {
  const dict = strings[lang] || strings['ar'];
  let text = (dict as Record<string, string>)[key] || key;
  if (args.length > 0) {
    args.forEach((val, i) => {
      text = text.replace(`{${i}}`, String(val));
    });
  }
  return text;
}
